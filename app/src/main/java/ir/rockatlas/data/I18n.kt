package ir.rockatlas.data

import java.util.Locale

enum class Lang(val code: String, val rtl: Boolean, val nativeName: String) {
    FA("fa", true, "فارسی"),
    AR("ar", true, "العربية"),
    EN("en", false, "English"),
    RU("ru", false, "Русский"),
    ;

    companion object {
        fun fromCode(code: String?): Lang? = entries.firstOrNull { it.code == code }

        /** First launch: follow the phone's language when it is one of ours, else Persian. */
        fun fromDevice(): Lang = fromCode(Locale.getDefault().language) ?: FA
    }
}

